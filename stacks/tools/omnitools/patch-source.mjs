// Source edits made before `npm run build`. See the Dockerfile for why.
//
// Each edit names the exact text it expects. If an upstream release moves it,
// the build stops here with that edit's name rather than quietly shipping a page
// that still calls out.
import { execSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const SRC = '/app/src';

function edit(name, file, from, to) {
  const path = join(SRC, file);
  const text = readFileSync(path, 'utf8');
  const next = text.replace(from, to);
  if (next === text) throw new Error(`patch "${name}" no longer matches ${file}`);
  writeFileSync(path, next);
  console.log(`patched: ${name}`);
}

// The GitHub star button is an iframe from ghbtns.com on every page.
edit(
  'star button',
  'components/Navbar/index.tsx',
  /\s*<iframe\s+key="github-star"[\s\S]*?<\/iframe>,/,
  ''
);

// The image editor fetches its labels from a translation service and posts
// any label it is missing back to it. Its built-in English labels are enough.
edit(
  'image editor translations',
  'pages/tools/image/generic/editor/index.tsx',
  '<FilerobotImageEditor\n',
  '<FilerobotImageEditor\n                useBackendTranslations={false}\n'
);

// ── Icons ────────────────────────────────────────────────────────────────────
// @iconify/react downloads every icon from api.iconify.design as it is shown.
// Collect the icon names written in the source, bundle just those, and point
// the icon API at a path that does not exist, so a name this scan missed shows
// as a blank space instead of a call out.
function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, out);
    else if (/\.(tsx?|jsx?)$/.test(name)) out.push(path);
  }
  return out;
}

const wanted = new Map(); // prefix -> Set of names
const NAME = /['"`]([a-z0-9]+(?:-[a-z0-9]+)*):([a-z0-9]+(?:[-_][a-z0-9]+)*)['"`]/g;
for (const file of walk(SRC)) {
  for (const [, prefix, name] of readFileSync(file, 'utf8').matchAll(NAME)) {
    if (!wanted.has(prefix)) wanted.set(prefix, new Set());
    wanted.get(prefix).add(name);
  }
}

const tmp = mkdtempSync(join(tmpdir(), 'icons-'));
const collections = [];
let bundled = 0;
for (const [prefix, names] of wanted) {
  // Most "prefix:name" strings in the source are not icons at all (times,
  // URLs, i18n keys). Only prefixes that are real Iconify sets go further.
  let tarball;
  try {
    tarball = execSync(`npm pack @iconify-json/${prefix} --silent --pack-destination ${tmp}`, {
      stdio: ['ignore', 'pipe', 'ignore']
    }).toString().trim();
  } catch {
    continue;
  }
  const dir = join(tmp, prefix);
  execSync(`mkdir -p ${dir} && tar -xzf ${join(tmp, tarball)} -C ${dir}`);
  const set = JSON.parse(readFileSync(join(dir, 'package/icons.json'), 'utf8'));
  const subset = { prefix: set.prefix, icons: {}, aliases: {} };
  for (const key of ['width', 'height', 'left', 'top']) if (key in set) subset[key] = set[key];
  for (const name of names) {
    let current = name;
    // An alias points at a parent, possibly through other aliases.
    while (set.aliases?.[current] && !subset.aliases[current]) {
      subset.aliases[current] = set.aliases[current];
      current = set.aliases[current].parent;
    }
    if (set.icons[current]) {
      subset.icons[current] = set.icons[current];
      bundled++;
    }
  }
  if (Object.keys(subset.icons).length) collections.push(subset);
}
if (!bundled) throw new Error('patch "icons" found no icons in the source');

writeFileSync(
  join(SRC, 'offline-icons.ts'),
  `// Generated by media-stack's OmniTools build: the icons this app uses, so the
// page never asks api.iconify.design for them.
import { addAPIProvider, addCollection } from '@iconify/react';

const collections: Parameters<typeof addCollection>[0][] = ${JSON.stringify(collections)};

for (const collection of collections) addCollection(collection);
addAPIProvider('', { resources: [\`\${self.location.origin}/vendor/no-icon-api\`] });
`
);
edit('icons import', 'index.tsx', /^/, "import './offline-icons';\n");
console.log(`bundled ${bundled} icons from ${collections.length} sets`);
